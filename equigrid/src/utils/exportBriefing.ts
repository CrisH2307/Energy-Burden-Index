interface PillRenderOptions {
  label: string;
  backgroundColor: string;
  borderColor: string;
  textColor: string;
  fontSize: number;
  fontWeight: number;
  paddingX: number;
  height: number;
  borderRadius: number;
  borderWidth: number;
  uppercase?: boolean;
}

function roundRectPath(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  w: number,
  h: number,
  r: number,
): void {
  const radius = Math.min(r, w / 2, h / 2);
  ctx.beginPath();
  ctx.moveTo(x + radius, y);
  ctx.arcTo(x + w, y, x + w, y + h, radius);
  ctx.arcTo(x + w, y + h, x, y + h, radius);
  ctx.arcTo(x, y + h, x, y, radius);
  ctx.arcTo(x, y, x + w, y, radius);
  ctx.closePath();
}

/** Canvas-drawn pill — text is pixel-centered (html2canvas misaligns CSS text). */
function renderPillDataUrl(options: PillRenderOptions): string {
  const label = options.uppercase
    ? options.label.toUpperCase()
    : options.label;
  const font = `${options.fontWeight} ${options.fontSize}px "DM Sans", Arial, sans-serif`;

  const measureCanvas = document.createElement('canvas');
  const measureCtx = measureCanvas.getContext('2d');
  if (!measureCtx) return '';

  measureCtx.font = font;
  const textWidth = measureCtx.measureText(label).width;
  const cssWidth = Math.ceil(
    textWidth + options.paddingX * 2 + options.borderWidth * 2,
  );
  const cssHeight = options.height;
  const scale = 2;

  const canvas = document.createElement('canvas');
  canvas.width = cssWidth * scale;
  canvas.height = cssHeight * scale;

  const ctx = canvas.getContext('2d');
  if (!ctx) return '';

  ctx.scale(scale, scale);
  ctx.font = font;

  const inset = options.borderWidth / 2;
  const w = cssWidth - options.borderWidth;
  const h = cssHeight - options.borderWidth;

  roundRectPath(ctx, inset, inset, w, h, options.borderRadius);
  ctx.fillStyle = options.backgroundColor;
  ctx.fill();

  if (options.borderWidth > 0) {
    roundRectPath(ctx, inset, inset, w, h, options.borderRadius);
    ctx.strokeStyle = options.borderColor;
    ctx.lineWidth = options.borderWidth;
    ctx.stroke();
  }

  ctx.fillStyle = options.textColor;
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';
  ctx.fillText(label, cssWidth / 2, cssHeight / 2);

  return canvas.toDataURL('image/png');
}

function pillImgHtml(
  dataUrl: string,
  alt: string,
  heightPx: number,
  marginCss: string,
): string {
  return (
    `<img src="${dataUrl}" alt="${alt}" ` +
    `style="display:block;${marginCss}height:${heightPx}px;width:auto;border:0;" />`
  );
}

function buildTierBadgeHtml(nb: Neighbourhood): string {
  const tc = TIER_COLORS[nb.tier];
  const label = TIER_LABELS[nb.tier].short;
  const dataUrl = renderPillDataUrl({
    label,
    backgroundColor: tc.light,
    borderColor: tc.bg,
    textColor: tc.text,
    fontSize: 13,
    fontWeight: 700,
    paddingX: 16,
    height: 31,
    borderRadius: 15,
    borderWidth: 1.5,
  });
  if (!dataUrl) return label;
  return pillImgHtml(dataUrl, label, 31, 'margin:0 auto;');
}

function buildProgramRoleBadgeHtml(role: 'Primary' | 'Secondary'): string {
  const dataUrl = renderPillDataUrl({
    label: role,
    backgroundColor: 'rgba(255, 255, 255, 0.25)',
    borderColor: 'transparent',
    textColor: '#ffffff',
    fontSize: 9,
    fontWeight: 700,
    paddingX: 10,
    height: 23,
    borderRadius: 4,
    borderWidth: 0,
    uppercase: true,
  });
  if (!dataUrl) return role;
  return pillImgHtml(dataUrl, role, 23, 'margin:0 0 8px 0;');
}

function buildTemplateVars(nb: Neighbourhood): Record<string, string> {
  const tc = TIER_COLORS[nb.tier];
  const tierBg = tc.light;
  const tierBorder = tc.bg;
  const tierDot = tc.bg;
  const tierText = tc.text;
  const secondaryTotalImpact = Math.round(
    nb.eligible_households * nb.secondaryBenefit,
  );

  return {
    briefingDate: todayISO(),
    neighbourhoodName: nb.name,
    rank: String(nb.rank),
    totalNeighbourhoods: String(TOTAL_NEIGHBOURHOODS),
    ebiScore: nb.ebi.toFixed(3),
    tierLabel: TIER_LABELS[nb.tier].short,
    tierBadgeHtml: buildTierBadgeHtml(nb),
    primaryRoleBadgeHtml: buildProgramRoleBadgeHtml('Primary'),
    secondaryRoleBadgeHtml: buildProgramRoleBadgeHtml('Secondary'),
    tierBg,
    tierBorder,
    tierDot,
    tierText,
    incomeScore: nb.income.toFixed(3),
    renterScore: nb.renter.toFixed(3),
    consumptionScore: nb.consumption.toFixed(3),
    ageScore: nb.age.toFixed(3),
    incomeBarWidth: (nb.income * 100).toFixed(1),
    renterBarWidth: (nb.renter * 100).toFixed(1),
    consumptionBarWidth: (nb.consumption * 100).toFixed(1),
    ageBarWidth: (nb.age * 100).toFixed(1),
    renterPct: (nb.renter_pct * 100).toFixed(1),
    estKwh: nb.est_kwh.toLocaleString(),
    dominantDwelling: nb.dwelling,
    // Template placeholders (used by briefing_template.html)
    primaryProgramColor: PROGRAM_COLORS[nb.primaryKey].bg,
    primaryProgramName: nb.primaryName,
    primaryEligibility: nb.primaryEligibility,
    primaryBenefit: nb.primaryBenefit.toLocaleString(),
    primaryEligibleHH: nb.eligible_households.toLocaleString(),
    primaryTotalImpact: nb.total_annual_benefit.toLocaleString(),
    secondaryProgramColor: PROGRAM_COLORS[nb.secondaryKey].bg,
    secondaryProgramName: nb.secondaryName,
    secondaryEligibility: nb.secondaryEligibility,
    secondaryBenefit: nb.secondaryBenefit.toLocaleString(),
    secondaryEligibleHH: nb.eligible_households.toLocaleString(),
    secondaryTotalImpact: secondaryTotalImpact.toLocaleString(),
    projectedAmount: nb.total_annual_benefit.toLocaleString(),
    projectedHH: nb.eligible_households.toLocaleString(),

    // Legacy placeholders (not required by the current template)
    primaryProgramStyle: `background:${PROGRAM_COLORS[nb.primaryKey].bg}`,
    secondaryProgramStyle: `background:${PROGRAM_COLORS[nb.secondaryKey].bg}`,
  };
}

function applyTemplate(html: string, vars: Record<string, string>): string {
  let out = html;
  for (const [key, value] of Object.entries(vars)) {
    out = out.split(`{{${key}}}`).join(value);
  }
  return out;
}

function waitForIframeReady(iframe: HTMLIFrameElement): Promise<Document> {
  return new Promise((resolve, reject) => {
    const onLoad = () => {
      const doc = iframe.contentDocument;
      if (!doc) {
        reject(new Error('Export iframe has no document'));
        return;
      }
      resolve(doc);
    };
    iframe.addEventListener('load', onLoad, { once: true });
    setTimeout(() => {
      if (iframe.contentDocument?.body?.childElementCount) {
        onLoad();
      }
    }, 500);
  });
}

async function htmlBriefingToPdf(nb: Neighbourhood): Promise<void> {
  const response = await fetch('/briefing_template.html');
  if (!response.ok) {
    throw new Error(`Failed to load briefing template (${response.status})`);
  }

  const templateHtml = await response.text();
  const populatedHtml = applyTemplate(templateHtml, buildTemplateVars(nb));

  if (/\{\{[a-zA-Z]+\}\}/.test(populatedHtml)) {
    console.warn(
      '[exportBriefing] Unreplaced template placeholders:',
      populatedHtml.match(/\{\{[a-zA-Z]+\}\}/g),
    );
  }

  const iframe = document.createElement('iframe');
  iframe.setAttribute('aria-hidden', 'true');
  iframe.setAttribute('title', 'Briefing export');
  iframe.style.position = 'fixed';
  iframe.style.top = '0';
  iframe.style.left = '-794px';
  iframe.style.width = '794px';
  // Make the viewport taller than the template so the render isn't clipped.
  iframe.style.height = '2200px';
  iframe.style.border = 'none';
  iframe.style.pointerEvents = 'none';
  document.body.appendChild(iframe);

  const filename = `${nb.name.replace(/\s+/g, '_')}.pdf`;

  try {
    const doc = iframe.contentDocument;
    if (!doc) throw new Error('Could not create export iframe document');
    doc.open();
    doc.write(populatedHtml);
    doc.close();

    const readyDoc = await waitForIframeReady(iframe);
    await readyDoc.fonts?.ready;
    await new Promise((resolve) => setTimeout(resolve, 200));

    const target =
      (readyDoc.body.firstElementChild as HTMLElement | null) ??
      readyDoc.body;

    await html2pdf()
      .set({
        margin: 0,
        filename,
        image: { type: 'jpeg', quality: 0.98 },
        html2canvas: {
          scale: 2,
          useCORS: true,
          backgroundColor: '#ffffff',
          windowWidth: 794,
          windowHeight: 2200,
          scrollX: 0,
          scrollY: 0,
        },
        jsPDF: { unit: 'mm', format: 'a4', orientation: 'portrait' },
      })
      .from(target)
      .save();
  } finally {
    document.body.removeChild(iframe);
  }
}

export function exportBriefing(nb: Neighbourhood): void {
  htmlBriefingToPdf(nb).catch((err: unknown) => {
    console.error('[exportBriefing] PDF generation failed:', err);
  });
}

export function previewBriefing(nb: Neighbourhood): string {
  return buildBriefingMarkdown(nb);
}
